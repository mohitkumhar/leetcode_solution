class Solution:
    def countCommas(self, n: int) -> int:
        if n <= 999:
            return 0

        if n <= 999999:
            return n - 999

        if n <= 999999999:
            return (999999 - 999) + (n - 999999) * 2

        if n <= 999999999999:
            return (999999 - 999) + (999999999 - 999999) * 2 + (n - 999999999) * 3

        if n <= 999999999999999:
            return (
                (999999 - 999)
                + (999999999 - 999999) * 2
                + (999999999999 - 999999999) * 3
                + (n - 999999999999) * 4
            )

        return (
            (999999 - 999)
            + (999999999 - 999999) * 2
            + (999999999999 - 999999999) * 3
            + (999999999999999 - 999999999999) * 4
            + (n - 999999999999999) * 5
        )

# 0               - 999               -> 0
# 1000            - 999999            -> 1
# 1000000         - 999999999         -> 2
# 1000000000      - 999999999999      -> 3
# 1000000000000   - 999999999999999   -> 4
